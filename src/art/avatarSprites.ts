/// A 16x16 pixel character stored as ASCII art so it stays hand-editable.
/// Ported verbatim from ImposterApp/Avatars/AvatarSprite.swift.
///
/// Legend:
///   `.` transparent   `1` body   `2` body shade   `3` outline   `4` white   `5` accent
export interface AvatarSprite {
  id: string;
  name: string;
  rows: string[];
}

export const SPRITE_SIDE = 16;

/// Palette slot for a character, or null when transparent.
export function spriteSlot(character: string): number | null {
  const slot = '12345'.indexOf(character);
  return slot === -1 ? null : slot;
}


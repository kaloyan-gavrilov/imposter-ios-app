/// A 16x16 pixel icon for a word category, stored as ASCII art — same idea as
/// AvatarSprite, but each icon carries its own colours because category art is
/// fixed, never recoloured per player.
/// Ported verbatim from ImposterApp/Icons/CategoryIcon.swift.
///
/// Legend:
///   `.` transparent   `1` outline   `2` main   `3` shade   `4` light   `5` accent   `6` accent 2
export interface CategoryIcon {
  id: string;
  hexes: string[];
  rows: string[];
}

export const ICON_SIDE = 16;

/// Palette slot for a character, or null when transparent.
export function iconSlot(character: string): number | null {
  const slot = '123456'.indexOf(character);
  return slot === -1 ? null : slot;
}

